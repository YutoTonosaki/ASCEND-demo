import type {
  Exercise,
  Equipment,
  TrackingType,
  ExerciseCategory,
} from "../types/training";
// Difficulty is draft game metadata, not a scientific measurement or an active score.
function exercise(
  id: string,
  name: string,
  primary: BodyArea[],
  secondary: BodyArea[],
  equipment: Equipment[],
  trackingType: TrackingType,
  difficulty: number,
  progressionFamily: string,
  category: ExerciseCategory = "Strength",
): Exercise {
  return {
    id,
    name,
    primaryBodyParts: primary,
    secondaryBodyParts: secondary,
    equipment,
    trackingType,
    difficulty,
    progressionFamily,
    category,
    isCustom: false,
  };
}
